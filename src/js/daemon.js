// Every visitor gets a daemon: a name spoken by a Markov chain over a corpus
// of demons, constellations and stranger things. The chain keeps a separate
// transition table for every position in a name, and a seed string picks
// each letter, so one seed always names the same daemon.

import { seededRandom } from './random.js'

const addTransition = (table, last, next) => {
    table[last] = [...(table[last] || []), next]
}

// Position 0 holds first letters; position n maps a letter to the letters
// that followed it at n. 'end' marks where a name stopped.
export function buildChain(corpus) {
    const transitions = [[]]
    const at = (n) => (transitions[n] = transitions[n] || {})
    for (const name of corpus) {
        if (!name.length) continue
        transitions[0].push(name[0])
        for (let i = 1; i < name.length; i++) addTransition(at(i), name[i - 1], name[i])
        addTransition(at(name.length), name[name.length - 1], 'end')
    }
    return transitions
}

const pick = (options, seed) => options[Math.floor(seed * options.length)]

export function generateOne(transitions, seedString) {
    const name = [pick(transitions[0], seededRandom(seedString))]
    for (let i = 1; ; i++) {
        seedString = seedString + 'a'
        const next = pick((transitions[i] || {})[name[i - 1]] || [], seededRandom(seedString))
        if (next === 'end' || next === undefined) return name.join('')
        name.push(next)
    }
}

